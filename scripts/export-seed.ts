// Generates supabase/seed.sql from the bundled courses so the backend and the APK share one curriculum.
// Run: npx tsx scripts/export-seed.ts
import { writeFileSync } from 'node:fs';
import { EN_FOR_TA_SPEC, ES_FOR_EN_SPEC, SEED_COURSES } from '../data/seed';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (o: unknown) => `$json$${JSON.stringify(o)}$json$::jsonb`;

const out: string[] = ['-- Generated by scripts/export-seed.ts. Safe to re-run.', 'begin;'];
for (const spec of [EN_FOR_TA_SPEC, ES_FOR_EN_SPEC]) {
  out.push(
    `insert into public.courses (id, title, native_lang, target_lang, spec, published) values (${q(spec.id)}, ${q(spec.title)}, ${q(spec.native.code)}, ${q(spec.target.code)}, ${j(spec)}, true)` +
      ` on conflict (id) do update set title = excluded.title, spec = excluded.spec, published = true;`
  );
}
for (const c of SEED_COURSES) {
  c.units.forEach((u, ui) => {
    out.push(
      `insert into public.units (id, course_id, position, title, content) values (${q(u.id)}, ${q(c.id)}, ${ui + 1}, ${q(u.title)}, ${j({ subtitle: u.subtitle, section: u.section, guidebook: u.guidebook, roleplayIds: u.roleplayIds })})` +
        ` on conflict (id) do update set title = excluded.title, content = excluded.content;`
    );
    [...u.lessons.map((l) => ['lesson', l] as const), ['story', u.story] as const, ['timed', u.timed] as const].forEach(([kind, l], li) => {
      out.push(
        `insert into public.lessons (id, unit_id, position, kind, title, content) values (${q(l.id)}, ${q(u.id)}, ${li + 1}, ${q(kind)}, ${q(l.title)}, ${j({ vocab: l.vocab, exercises: l.exercises })})` +
          ` on conflict (id) do update set title = excluded.title, content = excluded.content;`
      );
    });
  });
}
out.push('commit;');
writeFileSync('supabase/seed.sql', out.join('\n') + '\n');
console.log('wrote supabase/seed.sql', (out.join('\n').length / 1024).toFixed(0) + ' KB');
